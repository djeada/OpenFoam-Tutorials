#!/usr/bin/env python3
"""Create two Foundation 6 cases and their Gmsh geometries (standard library only)."""
import argparse
import json
import math
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parent
SCENARIOS = ("wide_open", "tilted")
DEPTH = 0.1
ROOM_T = 293.15
OUTDOOR_T = 273.15
RADIATOR_T = 313.15


def geometry(tilted, mesh_size):
    """Connected polygon with an exterior region and a window passage.

    The tilted pane is a finite-thickness notch connected to the lower jamb.
    An embedded line at x=0 makes the room selection and flux plane exact.
    """
    top = (1.2 * math.sin(math.radians(10)), 1 + 1.2 * math.cos(math.radians(10)))
    lower = [(-2, 0), (-0.1, 0), (-0.1, 1), (0, 1)]
    if tilted:
        lower += [top, (top[0] + 0.04, top[1]), (0.04, 1), (0, 0.96)]
    points = lower + [
        (0, 0.8), (0, 0.2), (0, 0), (4, 0), (4, 2.5),
        (0, 2.5), (0, 2.2), (-0.1, 2.2), (-0.1, 2.5), (-2, 2.5),
    ]
    n = len(points)
    text = ["// Generated by prepare_cases.py; coordinates in metres.",
            "Mesh.MshFileVersion = 2.2;", "Mesh.ElementOrder = 1;"]
    for i, (x, y) in enumerate(points, 1):
        if -0.1 <= x <= 0.3:
            size = min(mesh_size, 0.012 if tilted and y > 2 and x < 0.3 else 0.03)
        else:
            size = mesh_size
        text.append(f"Point({i}) = {{{x:.12g}, {y:.12g}, 0, {size:.12g}}};")
    for i in range(1, n + 1):
        text.append(f"Line({i}) = {{{i}, {i % n + 1}}};")
    text += [f"Curve Loop(1) = {{{', '.join(map(str, range(1, n + 1)))}}};",
             "Plane Surface(1) = {1};"]
    a, b = points.index((0, 1)) + 1, points.index((0, 2.2)) + 1
    text += [f"Line({n + 1}) = {{{a}, {b}}};", f"Curve{{{n + 1}}} In Surface{{1}};",
             f"out[] = Extrude {{0, 0, {DEPTH}}} {{Surface{{1}}; Layers{{1}}; Recombine;}};",
             'Physical Volume("air") = {out[1]};',
             'Physical Surface("frontAndBack") = {1, out[0]};']
    patches = {"walls": [], "radiator": [], "outdoor": []}
    for i, (p, q) in enumerate(zip(points, points[1:] + points[:1])):
        far_side = p[1] == q[1] and p[1] in (0, 2.5) and max(p[0], q[0]) <= -0.1
        if p[0] == q[0] == -2 or far_side:
            patch = "outdoor"
        elif p == (0, 0.8) and q == (0, 0.2):
            patch = "radiator"
        else:
            patch = "walls"
        patches[patch].append(f"out[{i + 2}]")
    for patch, faces in patches.items():
        text.append(f'Physical Surface("{patch}") = {{{", ".join(faces)}}};')
    # Sash plus triangular attachment below the sill, all inside nominal room.
    sash_area = 0.04 * (top[1] - 1) + 0.5 * 0.04 * 0.04 if tilted else 0
    volume = (4 * 2.5 - sash_area) * DEPTH
    return "\n".join(text) + "\n", volume


def positive(value):
    value = float(value)
    if not math.isfinite(value) or value <= 0:
        raise argparse.ArgumentTypeError("must be a positive finite number")
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--end-time", type=positive, default=300, help="physical seconds (default 300)")
    parser.add_argument("--write-interval", type=positive, default=5, help="physical seconds (default 5)")
    parser.add_argument("--mesh-size", type=positive, default=0.08, help="far-field mesh size in metres")
    args = parser.parse_args()
    if args.write_interval > args.end_time:
        parser.error("--write-interval must not exceed --end-time")
    if not math.isclose(args.end_time / args.write_interval,
                        round(args.end_time / args.write_interval), abs_tol=1e-8):
        parser.error("--end-time must be an integer multiple of --write-interval")
    output = ROOT / "cases"
    if output.exists():
        parser.error("cases/ already exists; archive results or run ./Allclean before preparing again")
    output.mkdir()
    for scenario in SCENARIOS:
        case = output / scenario
        shutil.copytree(ROOT / "template", case)
        geo, volume = geometry(scenario == "tilted", args.mesh_size)
        (case / "constant" / "window.geo").write_text(geo)
        replacements = {"@END_TIME@": args.end_time, "@WRITE_INTERVAL@": args.write_interval,
                        "@ROOM_T@": ROOM_T, "@OUTDOOR_T@": OUTDOOR_T,
                        "@RADIATOR_T@": RADIATOR_T}
        for path in case.rglob("*"):
            if path.is_file():
                content = path.read_text()
                for token, value in replacements.items():
                    content = content.replace(token, f"{value:g}")
                path.write_text(content)
        metadata = dict(scenario=scenario, end_time=args.end_time,
                        write_interval=args.write_interval, mesh_size=args.mesh_size,
                        room_volume=volume, room_temperature=ROOM_T,
                        outdoor_temperature=OUTDOOR_T, radiator_temperature=RADIATOR_T)
        (case / "case_info.json").write_text(json.dumps(metadata, indent=2) + "\n")
        print(f"Prepared {scenario}: room air volume {volume:.8g} m^3")


if __name__ == "__main__":
    main()
